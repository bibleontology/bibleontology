"""THE COPYRIGHT DEPOSIT, AS ONE PDF (2026-10-16: at eCO's upload step the
deposit was needed as one PDF).

Identifying material for a database, not the whole, and nothing private:
  1. the upper ontology as published at bibleontology.org/ns: the meaning
     layer, the relation vocabulary and the structure layer, verbatim, with
     the version and date they carry;
  2. 50 representative records (ten each of people, places, events, concepts
     and stories told across passages), each with its cited verses and links,
     as the site's own answer gives them (credits scrubbed as for any reader);
  3. one page on how the records are organised.
Everything in it is already public on the site. No code, no interface.

    python tools/copyright_deposit.py   -> out/copyright/bible-ontology-deposit-<date>.pdf
"""
import datetime as dt
import html
import json
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "app2"))
import server as S  # noqa: E402

EDGE = Path(r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe")
OUT = ROOT / "out" / "copyright"
e = html.escape

RECORDS = {
    "People": ["abraham", "moses", "david", "ruth", "rahab", "elijah", "mary_magdalene", "peter",
               "nicodemus", "joseph"],
    "Places": ["jerusalem", "bethlehem", "egypt", "jericho", "babylon", "nazareth", "damascus",
               "red_sea", "galilee", "bethany"],
    "Events": ["event_burning_bush", "event_red_sea_crossing", "event_tower_of_babel",
               "event_david_defeats_goliath", "event_daniel_in_the_lions_den", "event_last_supper",
               "event_pentecost", "event_good_samaritan", "event_prodigal_son", "event_nicodemus_conversation"],
    "Concepts": ["love", "faith", "grace", "covenant", "mercy", "sin", "salvation", "righteousness",
                 "wisdom", "prayer"],
    "Stories told across passages": ["arc_the_flood", "arc_the_golden_calf", "arc_the_passover",
                                     "arc_the_red_sea", "arc_the_call_of_moses", "arc_esther_and_purim",
                                     "arc_daniels_test", "arc_mary_magdalene_at_the_tomb",
                                     "arc_the_cross_and_the_resurrection", "arc_peter_raises_tabitha"],
}

ORGANISATION = """
<p>Bible Ontology is a knowledge graph of the 66 books of the Protestant canon, organised by an
upper ontology the author specified type by type. Every record cites the verses it rests on.</p>
<h3>The upper ontology (Part 1, in full)</h3>
<p><b>The meaning layer</b> sets out the classes of what the text speaks of (people, groups, places,
events, objects, concepts, sayings and the like) and the properties that relate them. <b>The relation
vocabulary</b> names every kind of link a record can carry, from kinship to who said what to whom.
<b>The structure layer</b> sets out the kinds of passage units, the relations between clauses and
units, and how a passage is set with its structure, its original-language words and its connections.</p>
<h3>How the records are organised (Part 2, a sample)</h3>
<ul>
<li><b>Records.</b> Each person, place, event, concept and saying is one record, joined to others only
by what the text says of them, each link with its verse.</li>
<li><b>What passages say, not where words occur.</b> A link records a claim the text makes, never the
mere presence of a word.</li>
<li><b>Passages grouped into units of meaning</b> rather than verses: a speech is one turn however many
verses it runs; a command and its carrying out are linked.</li>
<li><b>Stories told again</b> are set side by side step by step, with no claim about why.</li>
<li><b>Concept pages are organised by the original-language words</b> behind them, with different words
that English translates alike kept apart.</li>
<li><b>Contested passages</b> are set side by side without a verdict.</li>
<li><b>Twenty-four major themes in five groups</b>, each concept given one home.</li>
<li><b>Readings are marked as readings</b>: anything the text does not state outright is shown as a
reading, with how it was reached.</li>
</ul>
<p>Excluded from the claim, and identified here only as part of the identifying material: the Bible
text (public domain); the MACULA Hebrew and Greek data (Biblica, CC BY 4.0); STEP Bible and WordNet
data; and text and data generated by AI, including the records' descriptions and notes.</p>
"""


def record(eid):
    eid = S.d_canonical(eid) if hasattr(S, "d_canonical") else eid
    c = json.loads(S.answer("/api/entity", f"id={eid}").decode("utf-8"))
    if not c.get("found"):
        return None
    refs = c.get("refs") or []
    links = []
    for g in c.get("groups") or []:
        for it in g.get("items") or []:
            links.append(f"<li>{e(g.get('category') or '')}: {e(it.get('label') or '')} "
                         f"<b>{e(it.get('name') or '')}</b>"
                         + (f" <span class=r>({e(', '.join(it.get('refs') or []))})</span>" if it.get("refs") else "")
                         + "</li>")
            if len(links) >= 12:
                break
        if len(links) >= 12:
            break
    total = c.get("total_relations") or 0
    desc = S._plain(c.get("desc") or "")
    return (f"<div class=rec><h4>{e(c.get('name') or eid)} <span class=t>{e(c.get('type') or '')} · "
            f"https://bibleontology.org/e/{e(S._addr(eid))}</span></h4>"
            + (f"<p class=d>{e(desc[:420])}{'…' if len(desc) > 420 else ''}</p>" if desc else "")
            + f"<p class=v><b>Verses ({len(refs)}):</b> {e(', '.join(refs[:24]))}{' …' if len(refs) > 24 else ''}</p>"
            + (f"<p class=v><b>Links ({total}), the first {len(links)}:</b></p><ul>{''.join(links)}</ul>" if links else "")
            + "</div>")


def main():
    S.load()
    ver = json.loads((ROOT / "ontology" / "ns-version.json").read_text(encoding="utf-8"))
    today = dt.date.today().isoformat()
    vocab = []
    for name in ("meaning", "relation", "structure"):
        url = f"https://bibleontology.org/ns/{name}.ttl"
        # the site refuses Python's default agent (the crawler policy, Caddy)
        req = urllib.request.Request(url, headers={"User-Agent": "curl/8.0 (bible-ontology deposit)"})
        with urllib.request.urlopen(req, timeout=60) as r:
            ttl = r.read().decode("utf-8")
        vocab.append(f"<h2 class=pb>1.{len(vocab) + 1} The {name} vocabulary</h2>"
                     f"<p class=meta>As published at {e(url)} (version {e(ver['version'])}, {e(ver['date'])}); "
                     f"{len(ttl.splitlines()):,} lines, verbatim.</p><pre>{e(ttl)}</pre>")
    recs, made = [], 0
    for kind, ids in RECORDS.items():
        rows = [x for x in (record(i) for i in ids) if x]
        made += len(rows)
        recs.append(f"<h3>{e(kind)} ({len(rows)})</h3>{''.join(rows)}")
    page = f"""<!doctype html><html><head><meta charset="utf-8"><title>Bible Ontology: deposit</title><style>
@page{{size:Letter;margin:18mm 16mm}} body{{font:10.5pt/1.4 Georgia,serif;color:#111}}
h1{{font-size:20pt;margin:0 0 4pt}} h2{{font-size:14pt;margin:14pt 0 4pt}} h3{{font-size:12pt;margin:12pt 0 4pt}}
h4{{font-size:11pt;margin:8pt 0 2pt}} .t,.meta,.r{{color:#555;font-weight:normal;font-size:9pt}}
.pb{{page-break-before:always}} pre{{font:7.5pt/1.25 Consolas,monospace;white-space:pre-wrap;word-break:break-all}}
.rec{{border-top:1px solid #bbb;padding-top:4pt;page-break-inside:avoid}} .d,.v{{margin:2pt 0}} ul{{margin:2pt 0 2pt 16pt;padding:0}}
li{{margin:0}}</style></head><body>
<h1>Bible Ontology</h1>
<p class=meta>bibleontology.org · identifying material for registration of an unpublished work ·
prepared {e(today)} · author: Doug Egge</p>
<p>Contents. <b>Part 1:</b> the upper ontology, in full, as published: the meaning layer, the relation
vocabulary and the structure layer (version {e(ver['version'])}, dated {e(ver['date'])}). <b>Part 2:</b>
{made} representative records, ten each of people, places, events, concepts and stories told across
passages, each with its cited verses and its first links. <b>Part 3:</b> how the records are organised.
No software or interface is included.</p>
<h2>Part 3 first: how the records are organised</h2>{ORGANISATION}
<h2 class=pb>Part 1: the upper ontology</h2>{''.join(vocab)}
<h2 class=pb>Part 2: representative records</h2>
<p class=meta>Each as the site's own answer gives it at https://bibleontology.org/e/&lt;id&gt;. Descriptions are
abridged at 420 characters, verse lists at 24 and links at 12; the counts are of the whole record.</p>
{''.join(recs)}
</body></html>"""
    OUT.mkdir(parents=True, exist_ok=True)
    src = OUT / f"bible-ontology-deposit-{today}.html"
    pdf = OUT / f"bible-ontology-deposit-{today}.pdf"
    src.write_text(page, encoding="utf-8")
    subprocess.run([str(EDGE), "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={pdf}", src.resolve().as_uri()], check=True, timeout=300)
    print(f"{made} records; {pdf.relative_to(ROOT)} ({pdf.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
